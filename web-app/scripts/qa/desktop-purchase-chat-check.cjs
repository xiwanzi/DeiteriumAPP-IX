async (page) => {
  const passed = [], errors = [], payments = [];
  const check = (value, label) => { if (!value) throw new Error(label); passed.push(label); };
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/api/v1/store/orders", async route => {
    payments.push(route.request().postDataJSON());
    if (payments.length === 1) return route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({error:{code:"TEMPORARILY_UNAVAILABLE",message:"模拟连接中断，待核对原请求"}})});
    return route.fulfill({status:200,contentType:"application/json",body:JSON.stringify({data:{operation:{operationId:"operation_one",status:"COMPLETED",resourceType:"ORDER",resourceId:"order_one"},order:{orderId:"order_one",orderNo:"D-ISOLATED",fundsStatus:"PAID",amount:"24.60"}}})});
  });
  await page.route("**/api/v1/operations/**", route => route.fulfill({status:404,contentType:"application/json",body:JSON.stringify({error:{code:"NOT_FOUND",message:"原请求尚未收到"}})}));
  await page.goto("http://127.0.0.1:5246/");
  await page.locator(".shop-catalog-grid .foundation-card").first().click();
  await page.getByRole("heading", {name:"商品详情",exact:true}).first().waitFor();
  check(await page.locator(".product-thumbnails button").count() === 2, "product details show a gallery with selectable thumbnails");
  await page.getByRole("button", {name:"查看第 2 张商品图",exact:true}).click();
  check((await page.locator(".product-main-image > img").getAttribute("src")).includes("street-daylight"), "thumbnail selection changes full product image");
  await page.getByRole("spinbutton", {name:"购买数量",exact:true}).fill("0");
  check(await page.getByRole("button", {name:"立即购买",exact:true}).isDisabled(), "invalid purchase quantity cannot proceed");
  await page.getByRole("spinbutton", {name:"购买数量",exact:true}).fill("2");
  await page.screenshot({path:"output/playwright/purchase-detail-light.png"});
  await page.getByRole("button", {name:"立即购买",exact:true}).click();
  await page.getByRole("button", {name:"查看最终报价",exact:true}).click();
  await page.getByRole("button", {name:"确认付款",exact:true}).waitFor();
  check(payments.length === 0, "viewing server quote does not create a payment");
  check(await page.locator(".checkout-amount strong").innerText() === "24.60", "payment summary uses the exact authoritative quote amount");
  await page.screenshot({path:"output/playwright/purchase-quote-light.png"});
  await page.getByRole("button", {name:"确认付款",exact:true}).click();
  await page.getByRole("button", {name:"重试原请求",exact:true}).waitFor();
  const journal = await page.evaluate(() => Object.values(JSON.parse(sessionStorage.getItem("deuterium-business:fixture-admin")))[0]);
  check(journal.origin === "http://127.0.0.1:5246", "payment recovery stores browser origin instead of shadowed delivery location");
  check(payments.length === 1 && !(await page.getByRole("heading", {name:"付款已确认",exact:true}).count()), "unknown result remains pending and never automatically duplicates payment");
  await page.getByRole("button", {name:"重试原请求",exact:true}).click();
  await page.getByRole("heading", {name:"付款已确认",exact:true}).waitFor();
  check(payments.length === 2 && JSON.stringify(payments[0]) === JSON.stringify(payments[1]), "explicit retry reuses exactly the original request ID and quote");
  await page.getByRole("button", {name:"关闭弹窗",exact:true}).click();
  await page.getByRole("button", {name:"切换深色模式",exact:true}).click();
  await page.locator(".shop-catalog-grid .foundation-card").first().click();
  await page.screenshot({path:"output/playwright/purchase-detail-dark.png"});
  await page.setViewportSize({width:390,height:900});
  const fits = await page.locator(".product-detail-modal").evaluate(el => el.scrollWidth <= el.clientWidth + 2 && el.getBoundingClientRect().right <= innerWidth + 2);
  check(fits, "product purchase detail fits a narrow viewport");
  await page.screenshot({path:"output/playwright/purchase-detail-mobile.png"});
  await page.getByRole("button", {name:"关闭弹窗",exact:true}).click();
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole("button", {name:"切换浅色模式",exact:true}).click();
  await page.route("**/api/v1/checkout/quotes", route => route.fulfill({status:200,contentType:"application/json",body:JSON.stringify({data:{quoteId:"expired_quote",version:1,totalAmount:"12.30",expiresAt:new Date(Date.now()-5000).toISOString(),items:[]}})}));
  await page.locator(".shop-catalog-grid .foundation-card").first().click();
  await page.getByRole("button", {name:"立即购买",exact:true}).click();
  await page.getByRole("button", {name:"查看最终报价",exact:true}).click();
  await page.getByRole("button", {name:"重新获取报价",exact:true}).waitFor();
  check(await page.getByRole("button", {name:"确认付款",exact:true}).isDisabled(), "expired quotes cannot be submitted for payment");
  await page.getByRole("button", {name:"关闭弹窗",exact:true}).click();
  await page.routeWebSocket("**/api/v1/chat/ws", () => {});
  await page.goto("http://127.0.0.1:5246/information");
  await page.locator(".bubble").filter({hasText:"欢迎来主城看看新建筑。"}).waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll(".pc-message img.avatar")].some(img => img.complete && img.naturalWidth > 0));
  check(await page.locator(".pc-message img.avatar").count() === 1, "public message identities resolve their profile avatars");
  check(await page.locator(".pc-message span.avatar").count() === 1, "broken avatar falls back to the sender initial");
  await page.screenshot({path:"output/playwright/chat-avatar-light.png"});
  await page.getByRole("button", {name:"切换深色模式",exact:true}).click();
  await page.screenshot({path:"output/playwright/chat-avatar-dark.png"});
  check(errors.length === 0, `no React runtime errors: ${errors.join("; ")}`);
  return {passed,payments,errors};
}
