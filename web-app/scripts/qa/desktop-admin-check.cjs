async (page) => {
  const passed = [], errors = [], writes = [];
  const check = (value, label) => { if (!value) throw new Error(label); passed.push(label); };
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (["POST", "PUT", "DELETE"].includes(request.method()) && request.url().includes("/api/v1/")) writes.push({url: request.url(), body: request.postDataJSON()}); });
  await page.getByRole("heading", {name:"商店管理",exact:true}).waitFor();
  check(await page.locator(".catalog-table tbody tr").count() === 6, "desktop catalog displays all loaded products as table rows");
  await page.getByRole("combobox", {name:"商品状态",exact:true}).selectOption("DRAFT");
  check(await page.locator(".catalog-table tbody tr").count() === 1, "draft filter narrows product rows");
  await page.getByRole("combobox", {name:"商品状态",exact:true}).selectOption("ALL");
  await page.getByRole("combobox", {name:"商品分类筛选",exact:true}).selectOption("category_two");
  check(await page.locator(".catalog-table tbody tr").count() === 2, "category filter narrows product rows");
  await page.getByRole("combobox", {name:"商品分类筛选",exact:true}).selectOption("ALL");
  await page.getByRole("textbox", {name:"搜索管理商品",exact:true}).fill("不存在的商品");
  await page.getByRole("heading", {name:"没有匹配的商品"}).waitFor();
  await page.getByRole("textbox", {name:"搜索管理商品",exact:true}).fill("");
  await page.screenshot({path:"output/playwright/desktop-catalog-light.png",fullPage:true});
  await page.getByRole("button", {name:"编辑 / 预览",exact:true}).first().click();
  await page.getByRole("complementary", {name:"App 实时预览"}).waitFor();
  await page.getByRole("textbox", {name:"商品标题",exact:true}).fill("主城建造物资包 · 新版");
  check(await page.locator(".phone-copy h2").innerText() === "购买 主城建造物资包 · 新版", "phone title changes immediately with form input");
  await page.screenshot({path:"output/playwright/desktop-editor-light.png"});
  await page.getByRole("button", {name:"裁切尺寸",exact:true}).click();
  await page.locator(".crop-dimensions").waitFor();
  check((await page.locator(".crop-inspector").innerText()).includes("353 × 260 dp"), "detail crop uses Android 393dp viewport minus 40dp margins");
  await page.getByRole("button", {name:"推荐海报",exact:true}).click();
  check((await page.locator(".crop-inspector").innerText()).includes("308 × 405 dp"), "poster crop uses Android fixed frame");
  await page.screenshot({path:"output/playwright/desktop-crop-light.png"});
  await page.getByRole("button", {name:"双列卡片",exact:true}).click();
  await page.getByRole("combobox", {name:"模拟手机宽度",exact:true}).selectOption("430");
  check((await page.locator(".crop-inspector").innerText()).includes("189 × 170 dp"), "two-column crop updates for a wider phone");
  await page.getByRole("button", {name:"购物袋",exact:true}).click();
  check((await page.locator(".crop-inspector").innerText()).includes("80 × 100 dp"), "shopping bag crop uses Android thumbnail frame");
  await page.getByRole("button", {name:"商品详情",exact:true}).click();
  await page.getByRole("combobox", {name:"选择预览图片",exact:true}).selectOption("1");
  check((await page.locator(".crop-original img").getAttribute("src")).includes("street-daylight"), "gallery selection updates the crop image");
  await page.getByRole("textbox", {name:"邮件标题",exact:true}).fill("你的建造物资已送达");
  await page.getByRole("textbox", {name:"邮件正文",exact:true}).fill("感谢支持！\n请在生存服务器打开邮箱领取。");
  await page.getByRole("button", {name:"游戏邮件",exact:true}).click();
  check((await page.locator(".mail-preview").innerText()).includes("你的建造物资已送达") && (await page.locator(".mail-preview p").innerText()).includes("\n"), "mail preview retains custom title and line breaks");
  await page.screenshot({path:"output/playwright/desktop-mail-light.png"});
  await page.getByRole("button", {name:"关闭弹窗",exact:true}).click();
  check(await page.getByRole("dialog").count() === 1, "cancelling unsaved-close keeps the editor and its data");
  await page.getByRole("button", {name:"保存草稿",exact:true}).click();
  await page.getByText("草稿已保存", {exact:true}).waitFor();
  check(await page.getByRole("dialog").count() === 1, "saving a draft keeps the editing workspace open");
  const saved = writes.find(r => r.url.endsWith("/products/product_one"));
  check(saved.body.content.mailTitle === "你的建造物资已送达" && saved.body.content.mailBody.includes("\n"), "versioned product save includes game-mail fields");
  check(writes.filter(r => r.url.endsWith("/publish")).length === 0, "draft save never publishes automatically");
  await page.getByRole("button", {name:"保存并发布",exact:true}).click();
  await page.getByRole("dialog").waitFor({state:"hidden"});
  check(writes.filter(r => r.url.endsWith("/products/product_one")).length === 1 && writes.filter(r => r.url.endsWith("/publish")).length === 1, "publishing an unchanged saved draft reuses its version without duplicate saves");
  await page.getByRole("button", {name:"切换深色模式",exact:true}).click();
  await page.screenshot({path:"output/playwright/desktop-catalog-dark.png",fullPage:true});
  await page.getByRole("button", {name:"编辑 / 预览",exact:true}).first().click();
  await page.getByRole("button", {name:"预览深色",exact:true}).click();
  await page.screenshot({path:"output/playwright/desktop-editor-dark.png"});
  for (const width of [1280,1024,768,390,360,320]) {
    await page.setViewportSize({width,height:900});
    const fits = await page.locator(".product-editor-modal").evaluate(el => ({width:el.clientWidth,scroll:el.scrollWidth,right:el.getBoundingClientRect().right,screen:innerWidth}));
    check(fits.scroll <= fits.width + 2 && fits.right <= fits.screen + 2, `product editor stays within ${width}px viewport`);
    if (width === 390) await page.screenshot({path:"output/playwright/editor-mobile-dark.png"});
  }
  await page.getByRole("button", {name:"关闭弹窗",exact:true}).click();
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole("button", {name:"切换浅色模式",exact:true}).click();
  await page.getByRole("link", {name:"管理审计",exact:true}).click();
  await page.getByRole("heading", {name:"交易与玩家审计",exact:true}).waitFor();
  await page.getByRole("link", {name:"公告管理",exact:true}).click();
  await page.getByRole("heading", {name:"公告管理",exact:true}).waitFor();
  await page.goBack();
  await page.getByRole("heading", {name:"交易与玩家审计",exact:true}).waitFor();
  check(true, "management sections and browser back navigation stay synchronized");
  check(errors.length === 0, `no React runtime errors: ${errors.join("; ")}`);
  return {passed,writes:writes.map(({url,body})=>({path:url.split("5246")[1],requestId:body.clientRequestId})),errors};
}
